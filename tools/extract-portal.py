#!/usr/bin/env python3
"""Splits the approved design (preview/Corbit_X_Journey.html) into SPFx web part sources.
Run after editing the HTML design:  python3 tools/extract-portal.py   (first time: cd tools && npm i)"""
import re, json, hashlib, subprocess, os, base64, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'preview', 'Corbit_X_Journey.html')
OUT = os.path.join(ROOT, 'src', 'webparts', 'corbitXJourney', 'portal')
POSTERS = os.path.join(ROOT, 'seed', 'posters')
os.makedirs(OUT, exist_ok=True); os.makedirs(POSTERS, exist_ok=True)
s = open(SRC, encoding='utf8').read()

# the design is wrapped once by the preview tooling; use the inner document
inner = s.index('<style>\n:root')
css = s[inner + 7:s.index('</style>', inner)]
body_start = s.index('<div class="top">')
script_open = s.index('<script>', body_start)
markup = s[body_start:script_open]
script = s[script_open + 8:s.index('</script>', script_open)]

# ---- images -> assets table
URI = re.compile(r'data:image/[a-z+]+;base64,[A-Za-z0-9+/=]+')
assets, index = [], {}
def aid(uri):
    h = hashlib.md5(uri.encode()).hexdigest()
    if h not in index: index[h] = len(assets); assets.append(uri)
    return index[h]
markup = URI.sub(lambda m: '{{A%d}}' % aid(m.group(0)), markup)
poster_files = {}
poster_titles = {}
for m in re.finditer(r'(p\d+):\{title:"[^"]*", img:"(data:image/[a-z+]+;base64,[A-Za-z0-9+/=]+)"', script):
    head, b64 = m.group(2).split(',', 1); ext = 'png' if 'png' in head else 'jpg'
    poster_titles[m.group(1)] = re.search(m.group(1) + r':\{title:"([^"]*)"', script).group(1)
    open(os.path.join(POSTERS, m.group(1) + '.' + ext), 'wb').write(base64.b64decode(b64)); poster_files[m.group(1)] = m.group(1) + '.' + ext
script = re.sub(r'"(' + URI.pattern + r')"', lambda m: 'A[%d]' % aid(m.group(1)), script)

json.dump({k: {'title': poster_titles[k], 'file': v} for k, v in poster_files.items()}, open(os.path.join(ROOT, 'seed', 'posters.json'), 'w'), indent=1)
# ---- default list content
a = script.index('const LISTS = {'); b = script.index('const POSTERS = {')
lists_js = script[a:b]
open('/tmp/_lists.js', 'w').write(lists_js.replace('const LISTS =', 'globalThis.LISTS=') + '\nconsole.log(JSON.stringify(LISTS))')
lists = json.loads(subprocess.run(['node', '/tmp/_lists.js'], capture_output=True, text=True, check=True).stdout)
script = script[:a] + script[b:]
json.dump(lists, open(os.path.join(ROOT, 'seed', 'defaults.json'), 'w'), ensure_ascii=False, indent=1)

script = script.replace('const VOICE_BASE="voice/emily/";', 'const VOICE_BASE=(OPTS&&OPTS.voiceBase)||"voice/emily/";', 1)
assert 'OPTS&&OPTS.voiceBase' in script
# let the Posters list override poster titles/images
marker = 'const KHEAD='
assert marker in script
script = script.replace(marker, 'Object.keys(POSTER_OVERRIDES||{}).forEach(k=>{const o=POSTER_OVERRIDES[k];if(POSTERS[k]&&o){if(o.title)POSTERS[k].title=o.title;if(o.img)POSTERS[k].img=o.img}});\n' + marker, 1)

# ---- css: scope everything under .cxj
css = re.sub(r'(^|\n)html\{[^}]*\}', r'\1', css)
css = re.sub(r'html\{scroll-behavior:auto\}', '', css)
css = css.replace(':root{', '&{', 1)
css = re.sub(r'(^|\n)body\{', r'\1&{', css, count=1)
open('/tmp/_p.scss', 'w').write('.cxj{\n' + css + '\n}')
tc = os.path.join(ROOT, 'tools')
compiled = subprocess.run(['node', '-e', "const s=require('sass');process.stdout.write(s.compile('/tmp/_p.scss',{style:'compressed'}).css)"], capture_output=True, text=True, cwd=tc)
if compiled.returncode: sys.exit(compiled.stderr)
out_css = compiled.stdout

def w(name, text): open(os.path.join(OUT, name), 'w', encoding='utf8').write(text)
w('portalCss.ts', '// GENERATED by tools/extract-portal.py. Do not edit.\nexport const PORTAL_CSS: string = ' + json.dumps(out_css) + ';\n')
w('portalTemplate.ts', '// GENERATED by tools/extract-portal.py. Do not edit.\nexport const PORTAL_TEMPLATE: string = ' + json.dumps(markup) + ';\n')
w('portalAssets.ts', '// GENERATED by tools/extract-portal.py. Do not edit.\nexport const PORTAL_ASSETS: string[] = ' + json.dumps(assets) + ';\n')
w('defaultLists.ts', '// GENERATED by tools/extract-portal.py. Do not edit.\n/* eslint-disable */\nexport const DEFAULT_LISTS: any = ' + json.dumps(lists, ensure_ascii=False, indent=1) + ';\n')
w('runPortal.ts', '// GENERATED by tools/extract-portal.py from the approved design. Do not edit by hand.\n// @ts-nocheck\n/* eslint-disable */\nexport function runPortal(LISTS: any, POSTER_OVERRIDES: any, A: string[], OPTS: any): void {\n' + script + '\n}\n')
print('assets', len(assets), 'posters', poster_files, 'css', len(out_css), 'markup', len(markup), 'script', len(script))
